#!/usr/bin/env python3
"""PRIV-1/2: every state-changing external function of the deployable contracts, who may call it, and how long a change takes.

  privileged-functions.py check     fail when contracts/src has a state-changing external function (or a gate) that
                                    contracts/privileged-functions.json does not list, or when the generated roles table in
                                    .github/SECURITY.md is out of date                                        (CI)
  privileged-functions.py update    rewrite the manifest (keeping hand-written notes) and the SECURITY.md table
  privileged-functions.py table     print the markdown table

The function list comes from the built ABIs (contracts/out, run `forge build` first); the gate (role, owner, engine-only,
anyone) from the Solidity source of the function. A function whose gate this script cannot classify is reported as
`unclassified` and fails the check until it is understood and handled here.
"""
import json, re, subprocess, sys
from pathlib import Path

CONTRACTS = Path(__file__).resolve().parents[2]
MANIFEST = CONTRACTS / "privileged-functions.json"
SECURITY = CONTRACTS.parent / ".github" / "SECURITY.md"
START, END = "<!-- privileged-functions:start (generated by contracts/script/ci/privileged-functions.py) -->", "<!-- privileged-functions:end -->"

ROLE_DELAY = {
    "DEFAULT_ADMIN_ROLE": "48h timelock",
    "GUARDIAN_ROLE": "instant",
    "KEEPER_ROLE": "instant",
    "HEDGER_ROLE": "instant",
}
# Functions inherited from OpenZeppelin that are not in the contract source.
INHERITED = {
    "grantRole": "role:DEFAULT_ADMIN_ROLE", "revokeRole": "role:DEFAULT_ADMIN_ROLE",
    "renounceRole": "self",
    "transferOwnership": "owner", "acceptOwnership": "pending-owner", "renounceOwnership": "owner",
    "approve": "holder", "transfer": "holder", "transferFrom": "holder-or-approved",
}
# Who the caller really is when the gate is "anyone" but the function acts only on the caller's own position or on a
# signature. Notes are part of the generated table; a manifest note overrides these.
DEFAULT_NOTES = {
    "AgentRouter.buyFor(address,bytes32,uint128,uint128,uint64)": "the owner's agent key, inside its policy",
    "AgentRouter.sellFor(address,bytes32,uint128,uint128,uint64)": "the owner's agent key, inside its policy",
    "AgentRouter.shieldFor(address,address,uint128,uint16,uint128,uint64)": "the owner's agent key, inside its policy",
    "AgentRouter.setPolicy(address,uint128,uint128,uint64,bool,bool,address[])": "acts on the caller's own policy",
    "AgentRouter.revoke(address)": "acts on the caller's own agents",
    "AgentRouter.cancelQueuedFor(uint256)": "the owner of that queued sell",
    "LemniscateEngine.cancelQueued(uint256)": "the ticket's seller only",
    "LemniscateEngine.sell(bytes32,uint128,uint128,uint64,address)": "sells the caller's own tokens; never paused",
    "WriterPool.requestWithdraw(uint256)": "burns the caller's own shares; never paused",
    "WriterPool.claim(uint256)": "pays the ticket's owner",
    "VolOracle.post(tuple,bytes)": "needs the vol signer's EIP-712 signature",
    "LemniscatePaymaster.deposit()": "funds the paymaster",
    "LemniscatePaymaster.validatePaymasterUserOp(tuple,bytes32,uint256)": "ERC-4337 entry point only",
    "LemniscatePaymaster.postOp(uint8,bytes,uint256,uint256)": "ERC-4337 entry point only",
    "PriceGuard.poke(address)": "records a price reading; cannot set one",
}


def function_blocks(source: str):
    """Yields (name, param_count, header, body) for each function in a Solidity source."""
    for m in re.finditer(r"\bfunction\s+(\w+)\s*\(", source):
        i, depth = m.end(), 1
        while depth and i < len(source):
            depth += {"(": 1, ")": -1}.get(source[i], 0)
            i += 1
        params = source[m.end(): i - 1]
        count = 0 if not params.strip() else params.count(",") + 1
        j = i
        while j < len(source) and source[j] not in "{;":
            j += 1
        header = source[i:j]
        body = ""
        if source[j] == "{":
            k, depth = j, 0
            while k < len(source):
                depth += {"{": 1, "}": -1}.get(source[k], 0)
                k += 1
                if depth == 0:
                    break
            body = source[j:k]
        yield m.group(1), count, header, body


def classify(header: str, body: str, source: str, helpers: dict) -> str:
    gates = []
    for role in re.findall(r"onlyRole\(\s*(\w+)\s*\)", header):
        gates.append(f"role:{role}")
    if re.search(r"\bonlyOwner\b", header):
        gates.append("owner")
    if re.search(r"\bonlyEngine\b", header):
        gates.append("contract:engine")
    if re.search(r"\binitializer\b", header):
        gates.append("once:initializer")
    text = body
    # Pull in the checks of an internal helper the body calls (e.g. _checkPauser).
    for call in set(re.findall(r"\b(_check\w+|_require\w+|_only\w+)\s*\(", body)):
        text += helpers.get(call, "")
    for role in re.findall(r"hasRole\(\s*(\w+)\s*,\s*msg\.sender\s*\)|_checkRole\(\s*(\w+)\s*\)", text):
        name = role[0] or role[1]
        if f"role:{name}" not in gates:
            gates.append(f"role:{name}")
    known = {"engine": "contract:engine", "pool": "contract:pool", "owner": "owner", "entry_point": "contract:entrypoint"}
    for name in re.findall(r"msg\.sender\s*(?:!=|==)\s*(?:address\()?\$?\.?([A-Za-z_]+)", text):
        gate = known.get(name.lower())
        if gate and gate not in gates:
            gates.append(gate)
    if re.search(r"\bNotEngine\b|\bonlyEngine\b", text) and "contract:engine" not in gates:
        gates.append("contract:engine")
    if re.search(r"\bNotPool\b", text) and "contract:pool" not in gates:
        gates.append("contract:pool")
    if not gates:
        return "anyone"
    # Role gates keep their order but are de-duplicated and sorted for a stable manifest.
    return "|".join(sorted(set(gates)))


def delay_for(gate: str) -> str:
    parts = []
    for g in gate.split("|"):
        if g.startswith("role:"):
            role = g[5:]
            parts.append(f"{role.replace('_ROLE', '').lower()} {ROLE_DELAY.get(role, 'instant')}")
        elif g == "owner":
            parts.append("owner (a Safe, 2-step ownership, no timelock)")
        elif g == "anyone":
            parts.append("none (permissionless)")
        elif g.startswith("contract:"):
            parts.append(f"{g[9:]} only")
        elif g in ("holder", "holder-or-approved", "self", "pending-owner", "once:initializer"):
            parts.append("n/a (caller's own balance, role or one-time setup)")
        else:
            parts.append(g)
    return " / ".join(parts)


def collect() -> dict:
    subprocess.run(["forge", "build", "--silent"], cwd=CONTRACTS, check=True)
    entries = {}
    for artifact in sorted((CONTRACTS / "out").glob("*/*.json")):
        try:
            data = json.loads(artifact.read_text())
        except ValueError:
            continue
        target = (data.get("metadata") or {}).get("settings", {}).get("compilationTarget", {})
        path, name = next(iter(target.items()), (None, None))
        if not path or not path.startswith("src/") or path.startswith(("src/interfaces/", "src/libs/", "src/engine/")):
            continue
        if name != artifact.stem:
            continue
        if not (CONTRACTS / path).exists():
            continue  # a stale artifact of a deleted source file
        source = (CONTRACTS / path).read_text()
        if re.search(rf"\blibrary\s+{name}\b", source) or re.search(rf"\binterface\s+{name}\b", source):
            continue
        blocks = [(n, c, h, b) for n, c, h, b in function_blocks(source)]
        helpers = {n: h + b for n, c, h, b in blocks if n.startswith(("_check", "_require", "_only"))}
        upgrade_gate = next((classify(h, b, source, helpers) for n, c, h, b in blocks if n == "_authorizeUpgrade"), None)
        for item in data["abi"]:
            if item.get("type") != "function" or item.get("stateMutability") in ("view", "pure"):
                continue
            fn = item["name"]
            sig = f"{fn}({','.join(i['type'] for i in item['inputs'])})"
            if fn in INHERITED:
                gate = INHERITED[fn]
            elif fn == "upgradeToAndCall" and upgrade_gate:
                gate = upgrade_gate
            else:
                matches = sorted(((h, b) for n, c, h, b in blocks if n == fn and c == len(item["inputs"])), key=lambda m: not m[1])
                if not matches:
                    gate = "unclassified"
                else:
                    gate = classify(matches[0][0], matches[0][1], source, helpers)
            entries[f"{name}.{sig}"] = {"contract": name, "function": sig, "gate": gate, "delay": delay_for(gate)}
    return entries


def render(entries: dict, notes: dict) -> str:
    rows = ["| Contract | Function | Who may call | Delay |", "| --- | --- | --- | --- |"]
    for key in sorted(entries):
        e = entries[key]
        note = notes.get(key, "")
        who = e["gate"].replace("|", " or ")
        rows.append(f"| {e['contract']} | `{e['function']}` | {who}{' (' + note + ')' if note else ''} | {e['delay']} |")
    return "\n".join(rows)


def main() -> int:
    mode = sys.argv[1] if len(sys.argv) > 1 else "check"
    entries = collect()
    previous = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {"functions": {}}
    notes = {**DEFAULT_NOTES, **{k: v["note"] for k, v in previous["functions"].items() if v.get("note")}}
    table = render(entries, notes)
    if mode == "table":
        print(table)
        return 0
    manifest = {"functions": {k: {**entries[k], **({"note": notes[k]} if k in notes else {})} for k in sorted(entries)}}
    unknown = [k for k in notes if k not in entries]
    if unknown:
        print("privileged-functions: note for a function that does not exist: " + ", ".join(unknown), file=sys.stderr)
    block = f"{START}\n{table}\n{END}"
    if mode == "update":
        MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
        text = SECURITY.read_text()
        if START in text:
            text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
            SECURITY.write_text(text)
        else:
            print("SECURITY.md has no generated table markers; add them where the table belongs", file=sys.stderr)
        return 0
    problems = []
    old = previous["functions"]
    for k in sorted(set(entries) | set(old)):
        if k not in old:
            problems.append(f"NEW function not in privileged-functions.json: {k} (gate {entries[k]['gate']})")
        elif k not in entries:
            problems.append(f"listed function no longer exists: {k}")
        elif old[k]["gate"] != entries[k]["gate"]:
            problems.append(f"gate changed for {k}: {old[k]['gate']} -> {entries[k]['gate']}")
        elif old[k].get("delay") != entries[k]["delay"]:
            problems.append(f"delay changed for {k}: {old[k].get('delay')} -> {entries[k]['delay']}")
    for k, e in entries.items():
        if e["gate"] == "unclassified":
            problems.append(f"gate of {k} could not be classified; teach privileged-functions.py about it")
    text = SECURITY.read_text()
    if START not in text or block not in text:
        problems.append("the roles table in .github/SECURITY.md is out of date (run privileged-functions.py update)")
    if problems:
        print("privileged-functions: FAILED", *problems, sep="\n  ", file=sys.stderr)
        print("Review each change, then run: contracts/script/ci/privileged-functions.py update", file=sys.stderr)
        return 1
    print(f"privileged-functions: ok ({len(entries)} state-changing functions listed)")
    return 0


sys.exit(main())
